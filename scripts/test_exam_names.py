import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from fetch_exams import is_exam

fails = []
def check(name, want):
    got = is_exam(name)
    print(('ok  ' if got == want else 'FAIL') + ' ' + ('시험   ' if want else '시험 아님 ') + name)
    if got != want:
        fails.append(name)

# ① 예전부터 시험으로 보던 이름(그대로 들어와야 함)
for n in ['기말고사', '2차 정기시험', '2학기 2회고사', '2차 지필평가', '기말고사(1,2)', '2학기고사', '정기고사(기말)', '지필고사', '1회고사', '2회시험']:
    check(n, True)
# ② v4에서 더한 모양 — 숫자가 뒤(지필2고사·정기2시험) · 괄호 · 정기 오타 · 학년말 · 학기중 · 전각 숫자
for n in ['2학기 지필2고사', '2학기 지필2고사(3학년)', '지필1고사', '2학기 지필2평가(1,2학년)', '정기2시험', '정기2고사',
          '2학기 (제2회) 고사', '1회(중간)고사', '2회(기말)고사', '2회 정시시험', '3학년 학년말고사', '3학년말고사',
          '3학년 학기중고사', '1,2년 ２차시험']:
    check(n, True)
# ③ 시험 아님 — 새 규칙으로도 들어오면 안 됨(수능·모의·학력평가·졸업고사·이의신청·평가회·실기·체력 등)
for n in ['대학수학능력시험', '수능시험일', '전국연합학력평가', '모의고사', '졸업고사', '3학년 졸업고사', '2학기 중간(졸업)고사',
          '총괄평가', '2학기총괄평가', '지필평가 이의신청기간', '정기시험이의신청기간', '교육과정평가회', '학교평가 주간',
          '미술과 실기고사', '학생건강체력평가(PAPS)', '영어듣기평가', '수행평가 마감', '신입생 반편성고사', '월례고사(3년)',
          '3학년 고사', '3학년 시험', '3학년 종합고사', '전년도 시험지 공개(점심시간-도서실)', '진급평가회', '학년말방학', '2학기 개학식']:
    check(n, False)
